#!/usr/bin/env python3
"""Turn each scene of a video script into narration audio with Gemini TTS.

    GEMINI_API_KEY=$(secret-tool lookup service gemini-api) \
        python tools/narrate.py _videos/05-generalisation            # every changed scene
    python tools/narrate.py _videos/05-generalisation --dry-run      # what would be sent
    python tools/narrate.py _videos/05-generalisation --retake 7,12  # new takes of 7 and 12

One request per scene, written to audio/scene-NN.wav with a sidecar scene-NN.json.
A scene is regenerated only when what would be sent changes: its text after
respelling, the voice, the style, the language or the model. TTS output differs
slightly on every run, so an approved take must never be regenerated by accident;
use --retake to ask for a new one deliberately. The replaced take is kept in
audio/takes/.

The voice, style and language come from the script's front matter, and the
respellings from _videos/pronunciation.yml. The key is read from GEMINI_API_KEY and
nowhere else.
"""

import argparse
import base64
import json
import os
import re
import sys
import time
import wave
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from video_script import (LANGUAGE, MODEL, pronunciations, read_script,  # noqa: E402
                          request_key, respell)

# US dollars per million audio output tokens, for the running cost estimate.
PRICE_2026, PRICE_2027 = 9.0, 18.0

MAX_ATTEMPTS = 6


class DailyQuotaExhausted(Exception):
    pass


def parse_scenes(spec, count):
    chosen = set()
    for part in spec.split(","):
        a, _, b = part.strip().partition("-")
        chosen.update(range(int(a), int(b or a) + 1))
    bad = sorted(n for n in chosen if not 1 <= n <= count)
    if bad:
        sys.exit(f"no such scene: {bad} (the script has {count})")
    return chosen


def retry_delay(error, attempt):
    """Seconds to wait after a rate-limit or server error."""
    m = re.search(r"retryDelay'?\"?:\s*'?\"?(\d+(?:\.\d+)?)s", str(error))
    if m:
        return float(m.group(1)) + 1
    headers = getattr(getattr(error, "response", None), "headers", None) or {}
    if headers.get("retry-after", "").isdigit():
        return float(headers["retry-after"]) + 1
    return min(10 * 2 ** attempt, 120)


def synthesise(client, spoken, voice, style, language, model):
    """One scene, with retries. Returns (wav bytes, output tokens)."""
    from google.genai._gaos.lib.compat_errors import APIConnectionError, APIStatusError

    content = {"type": "text", "text": spoken}
    if style:
        content["annotations"] = [{"type": "speech_metadata", "style": style}]

    for attempt in range(MAX_ATTEMPTS):
        try:
            response = client.interactions.create(
                model=model,
                input=[content],
                response_modalities=["audio"],
                generation_config={"speech_config": [{"voice": voice, "language": language}]},
                response_format={"type": "audio", "mime_type": "audio/wav"},
            )
            break
        except APIStatusError as error:
            status = error.status_code
            if status == 429 and "PerDay" in str(error):
                raise DailyQuotaExhausted(str(error)) from error
            if status != 429 and status < 500:
                raise
            wait = retry_delay(error, attempt)
        except APIConnectionError as error:
            wait = retry_delay(error, attempt)
        if attempt == MAX_ATTEMPTS - 1:
            raise RuntimeError(f"gave up after {MAX_ATTEMPTS} attempts")
        print(f"    rate-limited or server error, waiting {wait:.0f} s", flush=True)
        time.sleep(wait)

    audio = response.output_audio
    if audio is None or not audio.data:
        raise RuntimeError(f"no audio in the response (status {response.status})")
    data = audio.data if isinstance(audio.data, bytes) else base64.b64decode(audio.data)
    if data[:4] != b"RIFF":
        raise RuntimeError(f"expected a WAV file, got {audio.mime_type}")
    return data, response.usage.total_output_tokens


def keep_take(wav, audio_dir, scene):
    """Move a take that is about to be replaced into audio/takes/."""
    takes = audio_dir / "takes"
    takes.mkdir(exist_ok=True)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%f")
    wav.rename(takes / f"{scene.stem}-{stamp}.wav")


def wav_seconds(path):
    with wave.open(str(path)) as w:
        return w.getnframes() / w.getframerate()


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("video", type=Path, help="the video folder, e.g. _videos/05-generalisation")
    parser.add_argument("--scenes", help="only these scenes, e.g. 3,5-7")
    parser.add_argument("--retake", metavar="SCENES",
                        help="generate a new take of these scenes even if unchanged, e.g. 7,12")
    parser.add_argument("--dry-run", action="store_true",
                        help="show what would be sent and which scenes are cached; no API calls")
    args = parser.parse_args()

    script = read_script(args.video / "script.md")
    voice = script.meta.get("voice") or sys.exit("script.md front matter needs a voice")
    style = script.meta.get("style", "")
    language = script.meta.get("language", LANGUAGE)
    model = script.meta.get("model", MODEL)
    table = pronunciations()

    count = len(script.scenes)
    only = parse_scenes(args.scenes, count) if args.scenes else None
    retake = parse_scenes(args.retake, count) if args.retake else set()

    audio_dir = args.video / "audio"
    audio_dir.mkdir(exist_ok=True)

    # Every take on disk, by what was sent for it, so a scene that was renumbered or
    # moved reuses its approved take instead of asking for a new one. Read up front:
    # the files are about to be moved around.
    existing = {}
    for sidecar in audio_dir.glob("scene-*.json"):
        info = json.loads(sidecar.read_text())
        wav = sidecar.with_suffix(".wav")
        if wav.exists():
            existing.setdefault(info["key"], (wav.read_bytes(), info))

    todo, reused = [], []
    for scene in script.scenes:
        if only and scene.number not in only and scene.number not in retake:
            continue
        spoken = respell(scene.narration, table)
        key = request_key(spoken, voice, style, language, model)
        wav, sidecar = audio_dir / f"{scene.stem}.wav", audio_dir / f"{scene.stem}.json"
        cached = (wav.exists() and sidecar.exists()
                  and json.loads(sidecar.read_text())["key"] == key)
        if cached and scene.number not in retake:
            continue
        if key in existing and scene.number not in retake:
            reused.append((scene, key, wav, sidecar))
            continue
        todo.append((scene, spoken, key, wav, sidecar))

    print(f"{script.path}: {count} scenes, {len(todo)} to generate, {len(reused)} reused "
          f"(voice {voice}, {language}, {model})")

    if args.dry_run:
        for scene, spoken, *_ in todo:
            print(f"\n  scene {scene.number}:\n    {spoken}")
        return

    for scene, key, wav, sidecar in reused:
        data, info = existing[key]
        if wav.exists():
            keep_take(wav, audio_dir, scene)
        wav.write_bytes(data)
        sidecar.write_text(json.dumps(info, ensure_ascii=False, indent=1) + "\n")
    if reused:
        print(f"  reused {len(reused)} unchanged take(s), now scene "
              f"{', '.join(str(s.number) for s, *_ in reused)}")

    if not todo:
        return
    api_key = os.environ.get("GEMINI_API_KEY") or sys.exit(
        "GEMINI_API_KEY is not set; see 'Storing the key' in .claude/videos.md")

    from google import genai
    # When the daily request quota is used up, the Interactions API hangs instead of
    # returning 429 (seen 2026-09-28); this timeout may not take effect, so wrap long
    # runs in `timeout`. See the Paid tier note in .claude/videos.md.
    client = genai.Client(api_key=api_key, http_options={"timeout": 120_000})

    tokens = 0
    for scene, spoken, key, wav, sidecar in todo:
        print(f"  scene {scene.number:2d} … ", end="", flush=True)
        try:
            data, used = synthesise(client, spoken, voice, style, language, model)
        except DailyQuotaExhausted:
            print("\nThe daily request quota is used up. Nothing was lost: rerun tomorrow, "
                  "or add billing, and the finished scenes will be skipped.")
            break

        if wav.exists():
            keep_take(wav, audio_dir, scene)

        wav.write_bytes(data)
        seconds = wav_seconds(wav)
        sidecar.write_text(json.dumps({
            "key": key, "spoken": spoken, "voice": voice, "style": style,
            "language": language, "model": model, "seconds": round(seconds, 2),
            "output_tokens": used,
            "created": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        }, ensure_ascii=False, indent=1) + "\n")
        tokens += used
        print(f"{seconds:5.1f} s, {used} tokens")

    print(f"\n{tokens} audio tokens this run: about ${tokens * PRICE_2026 / 1e6:.2f} "
          f"at the 2026 price, ${tokens * PRICE_2027 / 1e6:.2f} from 2027.")

    done = [audio_dir / f"{s.stem}.wav" for s in script.scenes]
    if all(p.exists() for p in done):
        total = sum(wav_seconds(p) for p in done) + sum(s.pause_after for s in script.scenes)
        print(f"All {count} scenes narrated: {total / 60:.1f} minutes including pauses.")


if __name__ == "__main__":
    main()
