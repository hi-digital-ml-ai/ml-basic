"""Loaders for the example datasets in data/, mirroring R/data.R.

The site's figures and tables are produced in R. These loaders exist so that the
Python tab of a code tabset is real, runnable code rather than pseudocode: the
same file, the same cleaning decisions, the same column names and factor level
order as the R page beside it.

Pages use them as:

    from mlbasic_data import load_coastal_survey_clean

Add a loader here whenever one is added to R/data.R, and keep the two in step.
"""

from pathlib import Path

import numpy as np
import pandas as pd

DATA_DIR = Path(__file__).resolve().parent.parent / "data"

# Factor level orders, matching R/data.R. The first level of a two-level response
# is the event, as tidymodels treats it; scikit-learn instead takes the *second*
# class as the positive one, which is why pages pass pos_label explicitly.
SEASONS = ["spring", "summer", "autumn", "winter"]
SUBSTRATES = ["sand", "mud", "gravel", "rock"]
YES_NO = ["yes", "no"]


def _categorical(series, levels):
    return pd.Categorical(series, categories=levels)


def load_coastal_survey():
    """Simulated coastal shelf survey, one row per station.

    SIMULATED data, generated by R/make-example-data.R. Any page using it must
    say so.
    """
    survey = pd.read_csv(DATA_DIR / "coastal-survey.csv")
    survey["season"] = _categorical(survey["season"], SEASONS)
    survey["substrate"] = _categorical(survey["substrate"], SUBSTRATES)
    survey["present"] = _categorical(survey["present"], YES_NO)
    return survey


def load_coastal_survey_raw():
    """The same survey as it came off the ship: 815 rows, with the damage intact.

    Read deliberately without cleaning — sentinel values, inconsistent labels and
    text dates all arrive as they are, because section 2 is about finding them.
    """
    return pd.read_csv(DATA_DIR / "coastal-survey-raw.csv")


def load_coastal_survey_clean():
    """The survey after the section 2 cleaning.

    Applies exactly the decisions argued for in section 2: drop duplicate rows,
    turn -999 sentinels into missing, correct the ten detectable decimal-point
    errors in depth, and collapse the twelve substrate spellings into four.
    Chlorophyll keeps its gaps — imputation belongs inside the resampling.
    """
    survey = load_coastal_survey_raw().drop_duplicates()

    survey["salinity_psu"] = survey["salinity_psu"].replace(-999, np.nan)
    survey["temperature_c"] = survey["temperature_c"].replace(-999, np.nan)
    survey["depth_m"] = survey["depth_m"].where(
        survey["depth_m"] <= 250, survey["depth_m"] / 10
    )

    substrate = survey["substrate"].str.strip().str.lower()
    survey["substrate"] = _categorical(
        substrate.replace({"sandy": "sand", "muddy": "mud", "rocky": "rock"}),
        SUBSTRATES,
    )
    survey["season"] = _categorical(survey["season"], SEASONS)
    survey["present"] = _categorical(survey["present"], YES_NO)
    survey["rare_species"] = _categorical(survey["rare_species"], YES_NO)

    return survey.reset_index(drop=True)


def load_coastal_survey_truth():
    """The true expected count behind each station, before noise was added.

    No real survey has this column. Join it on station_id. Never use it as a
    predictor, and never quote a metric computed against it as if it were
    achievable in practice.
    """
    return pd.read_csv(DATA_DIR / "coastal-survey-truth.csv")


def load_coastal_community():
    """Multi-taxon community matrix: station_id plus 24 taxon count columns."""
    return pd.read_csv(DATA_DIR / "coastal-community.csv")


def load_coastal_community_taxa():
    """The traits behind each taxon in load_coastal_community().

    It exists so section 8 can ask whether a discovered cluster corresponds to
    anything actually put into the data. Never feed it to a method as input.
    """
    return pd.read_csv(DATA_DIR / "coastal-community-taxa.csv")
